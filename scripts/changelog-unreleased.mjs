#!/usr/bin/env node
/**
 * Generates CHANGELOG.md sections from GitHub issues, grouped like the project
 * always has (see `.grenrc.json` → `groupBy`).
 *
 * Default mode keeps the `## [Unreleased]` section up to date from the closed
 * issues of the currently open (next) milestone. This is what you run while a
 * release is still in progress.
 *
 * `--release` renders the same issues as a dated, tag-linked section and
 * replaces the Unreleased block, which is what you run when cutting the release.
 *
 * Usage:
 *   GITHUB_TOKEN=$(gh auth token) npm run changelog:unreleased
 *   GITHUB_TOKEN=$(gh auth token) npm run generate-changelog     # --release
 *
 * Flags:
 *   --release   render a "## [vX.Y.Z](tree/vX.Y.Z) (dd/mm/yyyy)" section
 *               (version taken from the open milestone title)
 *   --dry-run   print the generated section instead of writing CHANGELOG.md
 *
 * A token is read from GITHUB_TOKEN / GREN_GITHUB_TOKEN, or from `gh auth token`.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const changelogPath = path.join(root, "CHANGELOG.md");
const grenrcPath = path.join(root, ".grenrc.json");
const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const release = args.includes("--release");

const grenrc = JSON.parse(fs.readFileSync(grenrcPath, "utf8"));
const { username, repo } = grenrc;
const groupBy = grenrc.groupBy ?? {};
const ignoreLabels = grenrc.ignoreIssuesWith ?? [];

function getToken() {
  const fromEnv =
    process.env.GITHUB_TOKEN ||
    process.env.GREN_GITHUB_TOKEN ||
    process.env.GH_TOKEN;
  if (fromEnv) return fromEnv;
  try {
    return execFileSync("gh", ["auth", "token"], { encoding: "utf8" }).trim();
  } catch {
    console.error(
      "No GitHub token. Set GITHUB_TOKEN (e.g. `GITHUB_TOKEN=$(gh auth token)`) and retry."
    );
    process.exit(1);
  }
}

const token = getToken();

async function api(urlPath) {
  const res = await fetch(`https://api.github.com${urlPath}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "User-Agent": "anywhere-ui-changelog",
    },
  });
  if (!res.ok) {
    throw new Error(`${res.status} ${res.statusText} for ${urlPath}`);
  }
  return res.json();
}

async function paginate(urlPath) {
  const items = [];
  for (let page = 1; ; page++) {
    const sep = urlPath.includes("?") ? "&" : "?";
    const batch = await api(`${urlPath}${sep}per_page=100&page=${page}`);
    items.push(...batch);
    if (batch.length < 100) break;
  }
  return items;
}

function compareVersions(a, b) {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d !== 0) return d;
  }
  return 0;
}

const milestones = await api(
  `/repos/${username}/${repo}/milestones?state=open&per_page=100`
);
const next = milestones
  .filter((m) => /^\d+\.\d+\.\d+$/.test(m.title))
  .sort((a, b) => compareVersions(b.title, a.title))[0];

if (!next) {
  if (release) {
    console.error("No open semantic-version milestone to release from.");
    process.exit(1);
  }
  console.log("No open semantic-version milestone — Unreleased section left as is.");
  process.exit(0);
}

const labelOf = (issue) =>
  (issue.labels ?? []).map((l) => (typeof l === "string" ? l : l.name));

const issues = (
  await paginate(
    `/repos/${username}/${repo}/issues?state=closed&milestone=${next.number}`
  )
)
  .filter((issue) => !issue.pull_request)
  .filter((issue) => !labelOf(issue).some((l) => ignoreLabels.includes(l)))
  .sort((a, b) => a.number - b.number);

const grouped = new Map();
for (const heading of Object.keys(groupBy)) grouped.set(heading, []);

const assigned = new Set();
for (const issue of issues) {
  const labels = labelOf(issue);
  for (const [heading, wanted] of Object.entries(groupBy)) {
    if (labels.some((l) => wanted.includes(l))) {
      grouped.get(heading).push(issue);
      assigned.add(issue.number);
      break;
    }
  }
}
const leftovers = issues.filter((i) => !assigned.has(i.number));
if (leftovers.length) grouped.set("Other Changes:", leftovers);

const issueLine = (issue) =>
  `- ${issue.title} [#${issue.number}](https://github.com/${username}/${repo}/issues/${issue.number})`;

let body = "";
for (const [heading, list] of grouped) {
  if (!list.length) continue;
  body += `\n **${heading}**\n\n`;
  body += list.map(issueLine).join("\n") + "\n";
}

function sectionFor(version) {
  if (!version) {
    return (
      `## [Unreleased]\n` +
      `<!-- generated by scripts/changelog-unreleased.mjs from milestone ${next.title} -->` +
      `\n${body}\n---\n`
    );
  }
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  const date = `${pad(now.getDate())}/${pad(now.getMonth() + 1)}/${now.getFullYear()}`;
  return (
    `## [v${version}](https://github.com/${username}/${repo}/tree/v${version}) (${date})\n` +
    `\n${body}\n---\n`
  );
}

const section = sectionFor(release ? next.title : null);

if (dryRun) {
  console.log(section);
  console.log(
    `\n(${issues.length} closed issues in milestone ${next.title}, ${leftovers.length} without a known label)`
  );
  process.exit(0);
}

const changelog = fs.readFileSync(changelogPath, "utf8");
const header = "# Changelog\n";

if (!changelog.startsWith(header)) {
  console.error(`CHANGELOG.md does not start with "${header.trim()}".`);
  process.exit(1);
}

const rest = changelog.slice(header.length).replace(/^\n+/, "");
const unreleasedRe = /^## \[Unreleased\][\s\S]*?(?=\n## \[|$)/;

let nextText;
if (unreleasedRe.test(rest)) {
  nextText = rest.replace(unreleasedRe, section.replace(/\n---\n$/, "\n"));
} else {
  nextText = `${section}\n${rest}`;
}

fs.writeFileSync(
  changelogPath,
  `${header}\n${nextText.replace(/\n{3,}/g, "\n\n")}`
);

console.log(
  (release ? `Released ${next.title}` : `Updated "Unreleased"`) +
    ` in CHANGELOG.md from milestone ${next.title}: ${issues.length} closed issues ` +
    `(${leftovers.length} without a known label).`
);
